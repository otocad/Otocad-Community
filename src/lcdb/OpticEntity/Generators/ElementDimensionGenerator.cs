        /// <summary>
        /// 生成标注Entity列表（从Element - 新方法）
        /// </summary>
        /// <param name="element">Element对象</param>
        /// <returns>标注Entity列表</returns>
        public static List<Entity> GenerateDimensions(Element element)
        {
            var entities = new List<Entity>();

            if (element == null || !element.AutoGenerateDimensions)
                return entities;

            // 使用Element的标注点数据
            var dimensionPoints = element.GetDimensionPoints();
            if (dimensionPoints != null && dimensionPoints.DimCenterThickness1 != null)
            {
                return GenerateDimensionsFromPoints(element, dimensionPoints);
            }

            // 否则使用简化版本
            return GenerateSimpleDimensions(element);
        }

        /// <summary>
        /// 基于标注点生成完整标注
        /// </summary>
        private static List<Entity> GenerateDimensionsFromPoints(Element element, DimensionPointsData dimensionPoints)
        {
            var entities = new List<Entity>();

            // 判断透镜类型
            var lensType = DetermineLensType(element);
            var isDoubleConcave = lensType == LensType.DoubleConcave;
            var isDoubleConvex = lensType == LensType.DoubleConvex;
            var isMeniscus = lensType == LensType.Meniscus;
            var isPlanoConcave = lensType == LensType.PlanoConcave;
            var isPlanoConvex = lensType == LensType.PlanoConvex;

            // 1. 中心厚度标注 - 所有透镜都需要
            var centerThicknessDim = new LinearDimension(
                dimensionPoints.DimCenterThickness1,
                dimensionPoints.DimCenterThickness2,
                dimensionPoints.DimCenterThicknessOffset,
                Math.PI  // 水平方向（180度）
            );
            centerThicknessDim.Generate();
            entities.Add(centerThicknessDim);

            // 2. 全矢高标注 - 仅用于月牙透镜
            // 月牙透镜的特点是两个表面曲率方向相同
            if (isMeniscus &&
                dimensionPoints.DimSagFull1 != null && dimensionPoints.DimSagFull2 != null)
            {
                // 月牙透镜需要额外的全矢高标注
                var sagFullDim = new LinearDimension(
                    dimensionPoints.DimSagFull1,
                    dimensionPoints.DimSagFull2,
                    dimensionPoints.DimSagFullOffset,
                    Math.PI  // 水平方向
                );
                sagFullDim.Generate();
                entities.Add(sagFullDim);
            }

            // 3. 边缘厚度标注 - 月牙透镜或有明显边缘厚度差的透镜
            var edgeThickness = element.Thickness - CalculateSag(element.Surface1?.Radius ?? 0, element.SemiDiameter)
                              + CalculateSag(element.Surface2?.Radius ?? 0, element.SemiDiameter);

            if (Math.Abs(edgeThickness - element.Thickness) > 0.1 &&
                dimensionPoints.DimEdgeThicknessTop1 != null && dimensionPoints.DimEdgeThicknessTop2 != null)
            {
                var edgeThicknessDim = new LinearDimension(
                    dimensionPoints.DimEdgeThicknessTop1,
                    dimensionPoints.DimEdgeThicknessTop2,
                    Math.Max(20.0, element.SemiDiameter * 0.1),  // 向上偏移
                    0  // 水平方向（0度）
                );
                edgeThicknessDim.Generate();
                entities.Add(edgeThicknessDim);
            }

            // 4. 直径标注 - 使用标注点数据
            // 对于等直径透镜，只需要一个直径标注（通常在左侧）
            if (dimensionPoints.SingleLensType == SingleLensType.EqualDiameter)
            {
                if (dimensionPoints.DimSagLeft1 != null && dimensionPoints.DimSagLeft2 != null)
                {
                    var leftDiameterDim = new LinearDimension(
                        dimensionPoints.DimSagLeft1,
                        dimensionPoints.DimSagLeft2,
                        Math.Max(25.0, dimensionPoints.RealDiameter * 0.15),  // 偏移量
                        Math.PI / 2  // 垂直方向（90度）
                    );
                    leftDiameterDim.Generate();
                    entities.Add(leftDiameterDim);
                }
            }
            else
            {
                // 对于不等直径透镜，需要两个直径标注
                // 左侧直径标注
                if (dimensionPoints.DimSagLeft1 != null && dimensionPoints.DimSagLeft2 != null)
                {
                    var leftDiameterDim = new LinearDimension(
                        dimensionPoints.DimSagLeft1,
                        dimensionPoints.DimSagLeft2,
                        Math.Max(25.0, dimensionPoints.RealDiameter * 0.15),  // 偏移量
                        Math.PI / 2  // 垂直方向（90度）
                    );
                    leftDiameterDim.Generate();
                    entities.Add(leftDiameterDim);
                }

                // 右侧直径标注
                if (dimensionPoints.DimSagRight1 != null && dimensionPoints.DimSagRight2 != null)
                {
                    var rightDiameterDim = new LinearDimension(
                        dimensionPoints.DimSagRight1,
                        dimensionPoints.DimSagRight2,
                        Math.Max(25.0, dimensionPoints.RealDiameter2 * 0.15),  // 偏移量
                        Math.PI / 2  // 垂直方向
                    );
                    rightDiameterDim.Generate();
                    entities.Add(rightDiameterDim);
                }
            }

            return entities;
        }

        /// <summary>
        /// 判断透镜类型
        /// </summary>
        private static LensType DetermineLensType(Element element)
        {
            var r1 = element.Surface1?.Radius ?? 0;
            var r2 = element.Surface2?.Radius ?? 0;

            const double tolerance = 1e-10;

            // 平面检测
            var isFlat1 = Math.Abs(r1) < tolerance;
            var isFlat2 = Math.Abs(r2) < tolerance;

            if (isFlat1 && isFlat2)
                return LensType.Flat;

            if (isFlat1)
                return r2 > 0 ? LensType.PlanoConvex : LensType.PlanoConcave;

            if (isFlat2)
                return r1 > 0 ? LensType.PlanoConvex : LensType.PlanoConcave;

            // 曲面类型
            if (r1 > 0 && r2 < 0)
                return LensType.DoubleConvex;

            if (r1 < 0 && r2 > 0)
                return LensType.DoubleConcave;

            if ((r1 > 0 && r2 > 0) || (r1 < 0 && r2 < 0))
                return LensType.Meniscus;

            return LensType.Unknown;
        }

        /// <summary>
        /// 计算矢高
        /// </summary>
        private static double CalculateSag(double radius, double semiDiameter)
        {
            if (Math.Abs(radius) < 1e-10)
                return 0;

            if (semiDiameter >= Math.Abs(radius))
            {
                return radius > 0 ? Math.Abs(radius) : -Math.Abs(radius);
            }

            var sag = Math.Abs(radius) - Math.Sqrt(radius * radius - semiDiameter * semiDiameter);
            return radius > 0 ? sag : -sag;
        }

        /// <summary>
        /// 透镜类型枚举
        /// </summary>
        private enum LensType
        {
            Unknown,
            Flat,
            PlanoConvex,
            PlanoConcave,
            DoubleConvex,
            DoubleConcave,
            Meniscus
        }

        /// <summary>
        /// 生成简化版标注（当没有LensOutline时）
        /// </summary>
        private static List<Entity> GenerateSimpleDimensions(Element element)
        {
            var entities = new List<Entity>();

            var originX = element.OriginalX;
            var originY = element.OriginalY;
            var thickness = element.Thickness;
            var semiDiameter = element.SemiDiameter;
            var radius1 = element.Surface1?.Radius ?? 0.0;
            var radius2 = element.Surface2?.Radius ?? 0.0;

            // 计算矢高
            var sag1 = CalculateDimensionSag(radius1, semiDiameter);
            var sag2 = CalculateDimensionSag(radius2, semiDiameter);

            // 计算基于元素大小的动态间距
            var baseSpacing = Math.Max(20.0, semiDiameter * 0.2);

            // 1. 中心厚度标注
            var centerThicknessDim = new LinearDimension(
                new Vector2(originX + sag1, originY),
                new Vector2(originX + thickness + sag2, originY),
                baseSpacing * 1.5,
                Math.PI
            );
            centerThicknessDim.Generate();
            entities.Add(centerThicknessDim);

            // 2. 直径标注
            var diameterDim = new LinearDimension(
                new Vector2(originX + thickness / 2, originY - semiDiameter),
                new Vector2(originX + thickness / 2, originY + semiDiameter),
                baseSpacing * 2.0,
                Math.PI / 2  // 垂直方向（90度）
            );
            diameterDim.Generate();
            entities.Add(diameterDim);

            // 3. 边缘厚度标注（如果需要）
            var edgeThickness = thickness - sag1 + sag2;
            if (Math.Abs(edgeThickness - thickness) > 0.1)
            {
                var edgeThicknessDim = new LinearDimension(
                    new Vector2(originX, originY + semiDiameter),
                    new Vector2(originX + thickness, originY + semiDiameter),
                    baseSpacing,
                    0
                );
                edgeThicknessDim.Generate();
                entities.Add(edgeThicknessDim);
            }

            return entities;
        }

        /// <summary>
        /// 计算表面矢高（维度生成器专用）
        /// </summary>
        private static double CalculateDimensionSag(double radius, double semiDiameter)
        {
            if (Math.Abs(radius) < 1e-10)
                return 0;

            if (semiDiameter >= Math.Abs(radius))
            {
                return radius > 0 ? Math.Abs(radius) : -Math.Abs(radius);
            }

            var sag = Math.Abs(radius) - Math.Sqrt(radius * radius - semiDiameter * semiDiameter);
            return radius > 0 ? sag : -sag;
        }

