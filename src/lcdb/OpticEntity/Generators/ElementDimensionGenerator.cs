            var edgeY = points.TopY;

            var dim = new LinearDimension(
                new Vector2(points.Surface1SagX, edgeY),
                new Vector2(points.Surface2SagX, edgeY),
                20.0, // 向上偏移
                0 // 0度（水平）
            );

            dim.Generate();
            return dim;
        }

        /// <summary>
        /// 生成Sag标注
        /// </summary>
        private static LinearDimension GenerateSagDimension(Element element, DimensionPoints points)
        {
            // 仅在双凸或双凹透镜时生成
            if ((element.Surface1?.Radius ?? 0) * (element.Surface2?.Radius ?? 0) <= 0)
                return null;

            var dim = new LinearDimension(
                new Vector2(points.Surface1SagX, points.CenterY),
                new Vector2(points.Surface2SagX, points.CenterY),
                -50.0, // 偏移距离
                Math.PI // 180度
            );

            dim.Generate();
            return dim;
        }

        /// <summary>
        /// 生成粗糙度标记
        /// </summary>
        private static Roughness GenerateRoughnessMark(Element element, DimensionPoints points)
        {
            var roughness = new Roughness
            {
                Center = new Vector2(points.Surface1SagX, points.TopY),
                ControlPoint = new Vector2(points.Surface1SagX - 10, points.TopY)
            };

            return roughness;
        }

