        /// 生成直径标注
        /// </summary>
        private static List<Entity> GenerateDiameterDimensions(Element element, DimensionPoints points, SingleLensType lensType)
        {
            var dimensions = new List<Entity>();
            var baseSpacing = Math.Max(20.0, element.SemiDiameter * 0.1);

            // 左侧直径标注
            var leftDim = new LinearDimension(
                new Vector2(points.Surface1SagX, points.TopY),
                new Vector2(points.Surface1SagX, points.BottomY),
                baseSpacing,
                Math.PI / 2 // 90度（垂直）
            );
