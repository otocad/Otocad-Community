            {
                var rightDim = new LinearDimension(
                    new Vector2(points.Surface2SagX, points.TopY),
                    new Vector2(points.Surface2SagX, points.BottomY),
                    -baseSpacing,
                    Math.PI * 3 / 2 // 270度
                );
                rightDim.IsImportant = (lensType == SingleLensType.RightLarger);
                rightDim.Generate();
                dimensions.Add(rightDim);
            }

            return dimensions;
        }

        /// <summary>
        /// 生成边缘厚度标注
        /// </summary>
